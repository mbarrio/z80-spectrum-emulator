#define flg_is2(i) (i&4)			// issue 2 emulation
#define flg_dbl(i) (i&8)			// double irpt freq
#define flg_vidsynchr ((i&48)>>4)// 1=hvs, 3=lvs, 2=nrml
#define flg_joystick ((i&192)>>6)// Cursor,Kempston,Udef,Sinclair 2
	 WORD length;    // additional length (excluding this word) (total-32)
	 WORD pc2;		// program counter for version >1.45
	 BYTE hmode;		// hardware mode
#define hm_48k 	0
#define hm_48kif1 1
#define hm_samram 2
#define hm_48kmgt	3
#define hm_128k	4
#define hm_128kif1 5
#define hm_128kmgt 6
	BYTE hstate;	// bitwise state of 74ls259, or 07ffd
	BYTE if1paged;	// 0FF if if1 rom paged
	BYTE flg2;
#define flg2_remul 1		// R register emulation
#define flg2_ldir  2		// LDIR emulation
#define flg2_ayemu48k 4		// AY emulation in 48k modes
#define flg2_uspeech 8	// micro-speech emulation
	BYTE fffd;		// soundchip register select
	BYTE sregs[16];	// soundchip register values
	WORD tstatelo;		// lo T state down counter
	BYTE tstatehi;		// hi T state up counter
	BYTE specflg;		// flag byte for Spectator (0)
	BYTE mgtpaged;		// 0FF if mgt rom paged
	BYTE multipaged;	// 0FF if multiface rom paged
	BYTE loram;			// 0FF if 0-8191 is RAM
	BYTE hiram;			// 0FF if 8192-16383 is RAM
	WORD kbdmap[5];	// udef joystick mapping
	WORD kbdasc[5];	// ascii values
	BYTE mgttype;		// 0=disc+eps,1=+HP,16=Plus D
	BYTE inhbutton;	// 0=inh.button out, 0ff=in
	BYTE inhflag;		// 0=ram pageable, 0ff=not
