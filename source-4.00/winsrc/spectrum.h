#define rr_borclr(i) ((i&14)>>1) // border colour
#define rr_samrom(i) (i&16)		// samrom paged
#define rr_compressed(i) (i&32)	// data compressed
	WORD de,bca,dea,hla;
	WORD faa;		// reversed AF' register
	WORD iy,ix;
	BYTE iff,iff2;
	BYTE flg;
